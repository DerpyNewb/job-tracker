/// The sample rows. Also adds one row whose date is text ("late Sep 2026"), as a hand-typed date
/// would be, to show that the app keeps what it can't read as a date.
pub fn sample_sheet(today: NaiveDate) -> Sheet {
    let day = |offset: i64| DateCell::Date(today + Duration::days(offset));
    let mut rows: Vec<Application> = ROWS
        .iter()
        .map(|r| Application {
            company: r.company.into(),
            role: r.role.into(),
            date_applied: r.applied.map_or(DateCell::Empty, |d| day(-d)),
            location: r.location.into(),
            compensation: r.compensation.into(),
            status: Status::parse(r.status),
            next_step: r.next_step.into(),
            contact: r.contact.into(),
            link: r.link.into(),
            notes: r.notes.into(),
            source: r.source.into(),
            resume: r.resume.into(),
            follow_up: r.follow_up.map_or(DateCell::Empty, day),
            extra: vec![r.rounds.map_or(Cell::Empty, Cell::Number)],
        })
        .collect();
    rows.push(Application {
        company: "Dominican Hill Digital".into(),
        role: "Data Entry and Reporting".into(),
        date_applied: DateCell::Text("late Sep 2026".into()),
        location: "Remote".into(),
        status: Status::Applied,
        next_step: "Look for their reply in spam".into(),
        notes: "Exact date not recorded.".into(),
        source: "OnlineJobs.ph".into(),
        extra: vec![Cell::Empty],
        ..Application::default()
    });
    Sheet {
        rows,
        extra_headers: vec![EXTRA_HEADER.into()],
    }
}
